"""Evaluate the isnad/matn splitter against LK-Hadith-Corpus Bukhari (manually checked).

LK is not redistributable, so it is read from a local clone and never committed.
Both sides are compared in normalize()d form after stripping a leading Prophet formula,
because the two conventions differ on whether "سمعت رسول الله ﷺ يقول" belongs to the
chain (the content boundary is what matters for deduplication).
"""

import csv
import json
import re
from difflib import SequenceMatcher
from pathlib import Path

from .split import split_narration, strip_prophet_formula
from .textnorm import clean, normalize


def _lk_rows(lk_dir: Path):
    for f in sorted((lk_dir / "Bukhari").glob("*.csv")):
        with f.open(encoding="utf-8-sig") as fh:
            yield from csv.DictReader(fh)


def _start_words(s: str, n: int = 6) -> str:
    return " ".join(strip_prophet_formula(normalize(s)).split()[:n])


def evaluate(lk_dir: Path, raw_bukhari: Path, out_examples: int = 25) -> dict:
    ours = {}
    for h in json.loads(raw_bukhari.read_text())["hadiths"]:
        ours.setdefault(normalize(clean(h["text"]))[:120], h)

    stats = {"lk_rows": 0, "aligned": 0, "start_exact": 0, "start_close": 0, "matn_sim_ge_90": 0}
    misses = []
    for r in _lk_rows(lk_dir):
        stats["lk_rows"] += 1
        key = normalize(r["Arabic_Hadith"])[:120]
        h = ours.get(key)
        if h is None or not r["Arabic_Matn"].strip() or r["Arabic_Matn"] == "nan":
            continue
        stats["aligned"] += 1
        sp = split_narration(clean(h["text"]))
        gold, got = _start_words(r["Arabic_Matn"]), _start_words(sp.matn)
        if gold == got:
            stats["start_exact"] += 1
        g3, o3 = gold.split()[:3], got.split()[:3]
        if g3 == o3 or (g3 and " ".join(g3) in " ".join(got.split()[:8])) or (o3 and " ".join(o3) in " ".join(gold.split()[:8])):
            stats["start_close"] += 1
        elif len(misses) < out_examples:
            misses.append({"n": h["hadithnumber"], "gold": gold, "ours": got,
                           "isnad_tail": " ".join(normalize(sp.isnad).split()[-6:])})
        # Main-matn similarity: LK matn has no tail; compare against ours.
        sim = SequenceMatcher(None, normalize(r["Arabic_Matn"]), normalize(sp.matn), autojunk=False).ratio()
        if sim >= 0.9:
            stats["matn_sim_ge_90"] += 1
    a = max(stats["aligned"], 1)
    stats["start_exact_rate"] = round(stats["start_exact"] / a, 4)
    stats["start_close_rate"] = round(stats["start_close"] / a, 4)
    stats["matn_sim_ge_90_rate"] = round(stats["matn_sim_ge_90"] / a, 4)
    return {"stats": stats, "misses": misses}


def write_report(path: Path, result: dict) -> None:
    s = result["stats"]
    lines = [
        "# M0 isnad/matn split evaluation",
        "",
        "Generated by `python -m u6 eval-split`. Gold standard: LK-Hadith-Corpus, Bukhari folder",
        "(manually checked by its authors; used for validation only, never redistributed).",
        "Narrations are aligned to ours by their first 120 normalized characters.",
        "",
        "| metric | value |",
        "|---|---:|",
        f"| LK rows | {s['lk_rows']} |",
        f"| aligned to our records | {s['aligned']} |",
        f"| matn start identical (first 6 words) | {s['start_exact']} ({s['start_exact_rate']:.1%}) |",
        f"| matn start close (3-word overlap within 8 words) | {s['start_close']} ({s['start_close_rate']:.1%}) |",
        f"| matn similarity ≥ 0.90 | {s['matn_sim_ge_90']} ({s['matn_sim_ge_90_rate']:.1%}) |",
        "",
        "Both sides are compared after `normalize()` and after stripping a leading Prophet",
        "formula, because LK ends the isnad before \"سمعت رسول الله ﷺ يقول\" while we keep",
        "it in the isnad. Similarity is lower than start agreement partly because LK splits",
        "some multi-hadith entries into several rows and moves comments to a separate column.",
        "",
        "## Sample disagreements",
        "",
        "| # | gold matn starts | ours starts | our isnad ends |",
        "|---|---|---|---|",
    ]
    for m in result["misses"]:
        lines.append(f"| {m['n']} | {m['gold']} | {m['ours']} | {m['isnad_tail']} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
